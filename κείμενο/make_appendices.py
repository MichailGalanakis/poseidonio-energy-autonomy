def heating_profile_table() -> str:
    h = pd.read_csv(ROOT / "data" / "poseidonio_heating_hourly_typical_day.csv", comment="#")
    names = {"Jan": "Ιαν", "Feb": "Φεβ", "Mar": "Μαρ", "Apr": "Απρ", "May": "Μαϊ",
             "Oct": "Οκτ", "Nov": "Νοε", "Dec": "Δεκ"}
    df = pd.DataFrame({"Ώρα": [f"{int(x):02d}:00" for x in h["hour"]]})
    for k, v in names.items():
        df[v] = [gr(x, 1) for x in h[k]]
    return md_table(df, "Πίνακας Β.1: Τυπικό ωριαίο προφίλ θερμικής ενέργειας τελικής μορφής για θέρμανση πισινών και χώρων (kWth) — Ιούνιος–Σεπτέμβριος μηδενικό [17].")


def dhw_profile_table() -> str:
    d = pd.read_csv(ROOT / "data" / "poseidonio_dhw_hourly_profile.csv", comment="#")
    half = len(d) // 2
    left, right = d.iloc[:half].reset_index(drop=True), d.iloc[half:].reset_index(drop=True)
    df = pd.DataFrame({
        "Ώρα": [f"{int(x):02d}:00" for x in left["hour"]],
        "kWh καυσίμου": [gr(x, 1) for x in left["gas_kwh_fuel_mean"]],
        "Ώρα ": [f"{int(x):02d}:00" for x in right["hour"]],
        "kWh καυσίμου ": [gr(x, 1) for x in right["gas_kwh_fuel_mean"]],
    })
    return md_table(df, "Πίνακας Β.2: Μέσο ωριαίο προφίλ κατανάλωσης φυσικού αερίου για ΖΝΧ, Ιούνιος–Σεπτέμβριος [17].")


def cashflow_table() -> str:
    c = pd.read_csv(ROOT / "results" / "tab_cashflows_25y.csv")
    df = pd.DataFrame({k: (c[k] if k == "Έτος" else [gr(x) for x in c[k]]) for k in c.columns})
